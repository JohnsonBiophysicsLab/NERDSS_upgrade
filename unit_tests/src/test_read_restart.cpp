// -----------------------------------------------------------------------------
// Test 1: the [parameters] block.
//
// Criteria: every "keyword = value" line in the header must land in the matching
// Parameters member, in the order the parser consumes them.  simItr is also
// mirrored into params.itrRestartFrom by the routine.
// -----------------------------------------------------------------------------
void read_restart_test_parameters_block()
{
    std::cerr << "\n[TEST] read_restart_test_parameters_block\n"
              << "  Source:        src/io/read_restart.cpp\n"
              << "  Section:       parameter header (keyword = value lines)\n"
              << "  Pass criteria: each keyword value is stored in the matching\n"
              << "                 Parameters member and simItr is echoed into\n"
              << "                 params.itrRestartFrom.\n";

    const RRResult& r = rr_result();
    ASSERT_TRUE(r.fileOpened) << "the synthetic restart file could not be opened";

    // Iteration bookkeeping.
    EXPECT_EQ(r.params.nItr, 1000LL) << "nItr should be 1000";
    EXPECT_EQ(r.simItr, 250LL) << "simItr (the out-parameter) should be 250";
    EXPECT_EQ(r.params.itrRestartFrom, 250LL)
        << "itrRestartFrom must be set from the simItr line";
    EXPECT_DOUBLE_EQ(r.params.timeRestartFrom, 0.005) << "timeRestartFrom should be 0.005 s";

    // Species / complex counts.
    EXPECT_EQ(r.params.numMolTypes, 1) << "numMolTypes should be 1";
    EXPECT_EQ(r.params.numTotalSpecies, 3) << "numTotalSpecies should be 3";
    EXPECT_EQ(r.params.numTotalComplex, 2) << "numTotalComplex should be 2";
    EXPECT_EQ(r.params.numTotalUnits, 4u) << "numTotalUnits should be 4";
    EXPECT_EQ(r.params.numLipids, 0) << "numLipids should be 0";

    // Propagation / limits.
    EXPECT_DOUBLE_EQ(r.params.timeStep, 0.1) << "timeStep should be 0.1 us";
    EXPECT_EQ(r.params.max2DRxns, 5000) << "max2DRxns should be 5000";
    EXPECT_DOUBLE_EQ(r.params.overlapSepLimit, 0.25) << "overlapSepLimit should be 0.25 nm";
    EXPECT_DOUBLE_EQ(r.params.rMaxLimit, 12.5) << "rMaxLimit should be 12.5";
    EXPECT_DOUBLE_EQ(r.params.scaleMaxDisplace, 55.5) << "scaleMaxDisplace should be 55.5";

    // Output intervals / flags.
    EXPECT_EQ(r.params.timeWrite, 10LL) << "timeWrite should be 10";
    EXPECT_EQ(r.params.trajWrite, 20LL) << "trajWrite should be 20";
    EXPECT_EQ(r.params.restartWrite, 30LL) << "restartWrite should be 30";
    EXPECT_EQ(r.params.pdbWrite, 40LL) << "pdbWrite should be 40";
    EXPECT_TRUE(r.params.assocDissocWrite) << "assocDissocWrite should be true (read as 1)";
    EXPECT_EQ(r.params.checkPoint, 50LL) << "checkPoint should be 50";
    EXPECT_EQ(r.params.transitionWrite, 60LL) << "transitionWrite should be 60";
    EXPECT_TRUE(r.params.clusterOverlapCheck) << "clusterOverlapCheck should be true";

    // The two *optional* trailing keywords, handled by the getline/'=' loop.
    EXPECT_TRUE(r.params.rngwrite) << "RNGwrite = 1 should be picked up by the optional-key loop";
    EXPECT_EQ(r.params.bondedComplexWrite, 70LL)
        << "bondedComplexWrite = 70 should be picked up by the optional-key loop";

    // The line that terminates the optional-key loop holds lastUpdateTransition.
    ASSERT_EQ(r.statLastUpdateTransition.size(), 3u)
        << "three lastUpdateTransition entries were written";
    EXPECT_EQ(r.statLastUpdateTransition[0], 1LL);
    EXPECT_EQ(r.statLastUpdateTransition[1], 2LL);
    EXPECT_EQ(r.statLastUpdateTransition[2], 3LL);
}

// -----------------------------------------------------------------------------
// Test 2: the Membrane / boundary information embedded in the header.
//
// Criteria: the water box triple, the six-value "membrane info" record, the
// per-state free-lipid counts and the seven-value boundary record are all
// distributed to the correct Membrane members, and waterBox.volume is recomputed.
// -----------------------------------------------------------------------------
void read_restart_test_membrane_block()
{
    std::cerr << "\n[TEST] read_restart_test_membrane_block\n"
              << "  Source:        src/io/read_restart.cpp\n"
              << "  Section:       waterBox / membrane / boundary records\n"
              << "  Pass criteria: Membrane fields match the file and\n"
              << "                 waterBox.volume == x*y*z is recomputed.\n";

    const RRResult& r = rr_result();
    ASSERT_TRUE(r.fileOpened);

    // Water box and derived volume.
    EXPECT_DOUBLE_EQ(r.membraneObject.waterBox.x, 100.0) << "waterBox.x should be 100";
    EXPECT_DOUBLE_EQ(r.membraneObject.waterBox.y, 200.0) << "waterBox.y should be 200";
    EXPECT_DOUBLE_EQ(r.membraneObject.waterBox.z, 300.0) << "waterBox.z should be 300";
    EXPECT_DOUBLE_EQ(r.membraneObject.waterBox.volume, 100.0 * 200.0 * 300.0)
        << "volume must be recomputed as x*y*z by the parser";

    // Six-value implicit-lipid record.
    EXPECT_EQ(r.membraneObject.implicitlipidIndex, -1) << "implicitlipidIndex should be -1";
    EXPECT_EQ(r.membraneObject.nSites, 1) << "nSites should be 1";
    EXPECT_EQ(r.membraneObject.nStates, 2) << "nStates should be 2";
    EXPECT_EQ(r.membraneObject.No_free_lipids, 10) << "No_free_lipids should be 10";
    EXPECT_EQ(r.membraneObject.No_protein, 20) << "No_protein should be 20";
    EXPECT_DOUBLE_EQ(r.membraneObject.totalSA, 3000.5) << "totalSA should be 3000.5";

    // One free-lipid count per state; the vector is grown to nStates entries.
    ASSERT_EQ(r.membraneObject.numberOfFreeLipidsEachState.size(), 2u)
        << "nStates == 2 so exactly two per-state counts are read";
    EXPECT_EQ(r.membraneObject.numberOfFreeLipidsEachState[0], 5);
    EXPECT_EQ(r.membraneObject.numberOfFreeLipidsEachState[1], 6);

    // Seven-value geometry record.
    EXPECT_FALSE(r.membraneObject.implicitLipid) << "implicitLipid should be false";
    EXPECT_FALSE(r.membraneObject.TwoD) << "TwoD should be false";
    EXPECT_TRUE(r.membraneObject.isBox) << "isBox should be true";
    EXPECT_FALSE(r.membraneObject.isSphere) << "isSphere should be false";
    EXPECT_DOUBLE_EQ(r.membraneObject.sphereR, 0.0) << "sphereR should be 0";
    EXPECT_FALSE(r.membraneObject.hasCompartment) << "hasCompartment should be false";
    EXPECT_DOUBLE_EQ(r.membraneObject.compartmentR, 0.0) << "compartmentR should be 0";
}

