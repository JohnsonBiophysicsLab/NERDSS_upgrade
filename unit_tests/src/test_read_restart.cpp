/*! \file test_read_restart.cpp
 *
 * ### Unit test for ../src/io/read_restart.cpp
 *
 * The function under test is:
 *
 *     void read_restart(long long int& simItr, std::ifstream& restartFile,
 *                       Parameters& params, SimulVolume& simulVolume,
 *                       std::vector<Molecule>& moleculeList,
 *                       std::vector<Complex>& complexList,
 *                       std::vector<MolTemplate>& molTemplateList,
 *                       std::vector<ForwardRxn>& forwardRxns,
 *                       std::vector<BackRxn>& backRxns,
 *                       std::vector<CreateDestructRxn>& createDestructRxns,
 *                       std::vector<TransmissionRxn>& transmissionRxns,
 *                       std::map<std::string, int>& observablesList,
 *                       Membrane& membraneObject, copyCounters& counterArrays)
 *
 * It is a large, strictly positional text parser: every field of the restart
 * file must appear in exactly the order in which the routine consumes it.  The
 * strategy used here is therefore:
 *
 *   1. Synthesise a *minimal but complete* restart file whose layout matches the
 *      read order of the parser exactly (1 molecule template, 1 forward + 1 back
 *      reaction, 2 molecules, 2 complexes, 1 observable, counter arrays).
 *   2. Call read_restart() once on that file.
 *   3. Assert, section by section, that every value landed in the right member.
 *
 * Important notes about the code under test that shaped this test:
 *
 *   - read_restart() reads into several *static* members (MolTemplate::numMolTypes,
 *     MolTemplate::numEachMolType, MolTemplate::absToRelIface,
 *     Interface::State::totalNumOfStates, RxnBase::numberOfRxns,
 *     RxnBase::totRxnSpecies, Molecule::numberOfMolecules, Molecule::emptyMolList,
 *     Complex::numberOfComplexes, Complex::emptyComList and
 *     Parameters::lastUpdateTransition).  Those are shared with the whole test
 *     binary, so we snapshot them, clear them, run the parse, capture the parsed
 *     values, and then put the originals back.  All assertions are made against
 *     the captured copies.
 *   - The counterArrays event histograms are indexed *without* being resized
 *     (`counterArrays.events3D[i]`), so the caller is required to have sized them
 *     beforehand.  We pre-size them to the default eventArraySize (20), which is
 *     also the value written into the test file.
 *   - The SimulVolume block of the restart file is commented out in the source,
 *     so simulVolume must come back untouched - that is asserted too.
 *   - The parser calls exit(1) on a malformed reaction type and can throw from
 *     std::stod on a malformed angle field.  Neither path is exercised, because
 *     that would tear down the entire gtest binary.
 */

