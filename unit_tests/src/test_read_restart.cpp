// -----------------------------------------------------------------------------
// Everything read_restart() produced, including copies of the static members it
// writes into.  All assertions look at this snapshot.
// -----------------------------------------------------------------------------
struct RRResult {
    bool fileOpened { false };

    long long int simItr { -1 };
    Parameters params {};
    SimulVolume simulVolume {};
    std::vector<Molecule> moleculeList {};
    std::vector<Complex> complexList {};
    std::vector<MolTemplate> molTemplateList {};
    std::vector<ForwardRxn> forwardRxns {};
    std::vector<BackRxn> backRxns {};
    std::vector<CreateDestructRxn> createDestructRxns {};
    std::vector<TransmissionRxn> transmissionRxns {};
    std::map<std::string, int> observablesList {};
    Membrane membraneObject {};
    copyCounters counterArrays {};

    // captured statics
    unsigned statNumMolTypes { 0 };
    std::vector<int> statNumEachMolType {};
    std::vector<int> statAbsToRelIface {};
    int statTotalNumOfStates { 0 };
    unsigned statNumberOfRxns { 0 };
    int statTotRxnSpecies { 0 };
    int statNumberOfMolecules { 0 };
    int statNumberOfComplexes { 0 };
    std::vector<int> statEmptyMolList {};
    std::vector<int> statEmptyComList {};
    std::vector<long long int> statLastUpdateTransition {};
};

/*! \brief Write the synthetic restart file, parse it, and capture the results.
 *
 * Static members touched by the parser are snapshotted / cleared / restored so
 * that no other test in the suite is affected by this one.
 */
RRResult rr_build_result()
{
    std::cerr << "\n[SETUP] test_read_restart.cpp\n"
              << "  Writing a synthetic restart file to \"" << kRRFileName << "\"\n"
              << "  and parsing it with read_restart() (src/io/read_restart.cpp).\n";

    // 1. Emit the file.
    {
        std::ofstream out(kRRFileName);
        out << kRRFileContents;
    }

    RRResult res;

    // 2. Pre-size the event histograms; read_restart() indexes them directly.
    res.counterArrays.events3D.assign(kRREventArraySize, 0);
    res.counterArrays.events3Dto2D.assign(kRREventArraySize, 0);
    res.counterArrays.events2D.assign(kRREventArraySize, 0);

    // 3. Snapshot every static the parser writes to, then clear the containers so
    //    the captured values reflect only what this file provided.
    const unsigned savedNumMolTypes = MolTemplate::numMolTypes;
    const std::vector<int> savedNumEachMolType = MolTemplate::numEachMolType;
    const std::vector<int> savedAbsToRelIface = MolTemplate::absToRelIface;
    const int savedTotalNumOfStates = Interface::State::totalNumOfStates;
    const unsigned savedNumberOfRxns = RxnBase::numberOfRxns;
    const int savedTotRxnSpecies = RxnBase::totRxnSpecies;
    const int savedNumberOfMolecules = Molecule::numberOfMolecules;
    const int savedNumberOfComplexes = Complex::numberOfComplexes;
    const std::vector<int> savedEmptyMolList = Molecule::emptyMolList;
    const std::vector<int> savedEmptyComList = Complex::emptyComList;
    const std::vector<long long int> savedLastUpdate = Parameters::lastUpdateTransition;

    MolTemplate::numEachMolType.clear();
    MolTemplate::absToRelIface.clear();
    Molecule::emptyMolList.clear();
    Complex::emptyComList.clear();
    Parameters::lastUpdateTransition.clear();

    // 4. Parse.
    {
        std::ifstream in(kRRFileName);
        res.fileOpened = in.is_open();
        if (res.fileOpened) {
            read_restart(res.simItr, in, res.params, res.simulVolume, res.moleculeList,
                res.complexList, res.molTemplateList, res.forwardRxns, res.backRxns,
                res.createDestructRxns, res.transmissionRxns, res.observablesList,
                res.membraneObject, res.counterArrays);
        }
    }

    // 5. Capture the statics as parsed.
    res.statNumMolTypes = MolTemplate::numMolTypes;
    res.statNumEachMolType = MolTemplate::numEachMolType;
    res.statAbsToRelIface = MolTemplate::absToRelIface;
    res.statTotalNumOfStates = Interface::State::totalNumOfStates;
    res.statNumberOfRxns = RxnBase::numberOfRxns;
    res.statTotRxnSpecies = RxnBase::totRxnSpecies;
    res.statNumberOfMolecules = Molecule::numberOfMolecules;
    res.statNumberOfComplexes = Complex::numberOfComplexes;
    res.statEmptyMolList = Molecule::emptyMolList;
    res.statEmptyComList = Complex::emptyComList;
    res.statLastUpdateTransition = Parameters::lastUpdateTransition;

    // 6. Restore the statics so the rest of the suite sees the original state.
    MolTemplate::numMolTypes = savedNumMolTypes;
    MolTemplate::numEachMolType = savedNumEachMolType;
    MolTemplate::absToRelIface = savedAbsToRelIface;
    Interface::State::totalNumOfStates = savedTotalNumOfStates;
    RxnBase::numberOfRxns = savedNumberOfRxns;
    RxnBase::totRxnSpecies = savedTotRxnSpecies;
    Molecule::numberOfMolecules = savedNumberOfMolecules;
    Complex::numberOfComplexes = savedNumberOfComplexes;
    Molecule::emptyMolList = savedEmptyMolList;
    Complex::emptyComList = savedEmptyComList;
    Parameters::lastUpdateTransition = savedLastUpdate;

    // 7. Clean up the scratch file.
    std::remove(kRRFileName);

    std::cerr << "[SETUP] parse finished (file opened = " << std::boolalpha
              << res.fileOpened << ")\n";
    return res;
}

/*! \brief Parse the file exactly once and share the result with every test. */
const RRResult& rr_result()
{
    static const RRResult result = rr_build_result();
    return result;
}

